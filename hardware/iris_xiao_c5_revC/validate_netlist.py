"""Compare KiCad's actual exported network membership against the design manifest."""
from pathlib import Path
import json, xml.etree.ElementTree as ET
from collections import defaultdict, Counter
ROOT=Path(__file__).resolve().parent;OUT=ROOT/'output'
comps=json.loads((OUT/'connectivity.json').read_text())
expected={};nc=set()
for c in comps:
    if c['ref'].startswith('#'):continue
    for p in c['pins']:
        ident=(c['ref'],p['num'])
        if p['net'] is None:nc.add(ident)
        else:expected[ident]=p['net']
root=ET.parse(OUT/'native_netlist.xml').getroot();actual={};groups=defaultdict(set)
for net in root.findall('./nets/net'):
    name=net.attrib['name']
    for node in net.findall('node'):
        ident=(node.attrib['ref'],node.attrib['pin']);actual[ident]=name;groups[name].add(ident)
errors=[];net_name_changes={}
frozen=json.loads((ROOT/'design_manifest.json').read_text())
def intent(rows):
    return {c['ref']:{'value':c['value'],'footprint':c['footprint'],'pins':sorted((p['num'],p['name'],p['net'],p['type']) for p in c['pins'])} for c in rows}
if intent(comps)!=intent(frozen):errors.append('Generated symbol connectivity differs from frozen design manifest')
expected_groups=defaultdict(set)
for ident,name in expected.items():expected_groups[name].add(ident)
for ident,name in expected.items():
    if ident not in actual:errors.append([ident,'missing',name]);continue
    if actual[ident]!=name:
        if groups[actual[ident]]==expected_groups[name] and 'Net-(' in actual[ident]:
            net_name_changes[name]=actual[ident]
        else:errors.append([ident,'name or membership mismatch',name,actual[ident]])
for ident in nc:
    if ident in actual and len(groups[actual[ident]])>1:errors.append([ident,'NC connected',actual[ident]])
for name,group in groups.items():
    intents={expected.get(p) for p in group};intents.discard(None)
    if len(intents)>1:errors.append(['short',name,sorted(intents)])
ercpath=OUT/'ERC.json';erc=[]
if ercpath.exists():
    e=json.loads(ercpath.read_text());erc=[v for s in e['sheets'] for v in s['violations']]
report={'native_KiCad':'9.0.8','schematic_sheets':3,'manifest_pins':len(expected)+len(nc),'connected_pins':len(expected),'explicit_NC_pins':len(nc),'native_netlist_vs_manifest':'PASS' if not errors else 'FAIL','mismatches':errors,'unlabelled_internal_nets':net_name_changes,'ERC_by_type':dict(Counter(v['type'] for v in erc)),'ERC_by_severity':dict(Counter(v['severity'] for v in erc)),'hardware_tested':False,'note':'Internal group wires may use autogenerated names; exact pin membership is required. ERC and net comparison do not validate power ratings, analogue margins or NFC RF operation.'}
(OUT/'validation.json').write_text(json.dumps(report,ensure_ascii=False,indent=2))
print(json.dumps(report,ensure_ascii=False,indent=2))
if errors:raise SystemExit(1)
